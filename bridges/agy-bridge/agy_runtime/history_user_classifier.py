"""Pure full-body classifier for synthetic DSH user-history blocks (AD-001)."""

from __future__ import annotations

import re

_REMINDER_OPEN = "<system-reminder>"
_REMINDER_CLOSE = "</system-reminder>"
_HARD_TAGS = (
    "<goal_round>",
    "<goal_blocked>",
    "<goal_complete>",
    "<compacted-summary>",
)
_RUNTIME_PREFIXES = (
    "Current runtime context. This snapshot supersedes earlier snapshots.",
    "Current runtime context. This snapshot supersedes earlier runtime-context snapshots.",
)
_NOTICE_RE = re.compile(
    r"The user (?:approved|rejected)(?: the)? (?:bash|command|tool)"
    r"(?: command| call)?(?:\.)?",
    re.IGNORECASE,
)
_JOB_HEAD_RE = re.compile(
    r"background job [^\s()\r\n]+ \([^()\r\n]*\) finished "
    r"\[status: [^\]\r\n]+\]\."
)
_REPEATED_CALL_NAME_RE = re.compile(r"[A-Za-z0-9_.:/-]+", re.ASCII)
_REPEATED_CALL_ARG_RE = re.compile(
    r"[A-Za-z0-9_.-]+=(?:[A-Za-z0-9_./:@-]+|\"[^\"()]*\"|'[^'()]*')", re.ASCII)
_EXACT_REPEAT_NOTICES = (
    "You are repeating the exact same tool call with identical arguments. "
    "Carefully analyze the previous result before calling again: if the task is not "
    "complete, try a different approach or different arguments instead of repeating the call.",
    "You are repeating the exact same tool call. Reconsider your approach.",
)
_JOB_OUTPUT_MARKERS = (
    "\nOutput:\n",
    "\n\nOutput:\n",
    "\nstdout:\n",
    "\n\nstdout:\n",
    "\nstderr:\n",
    "\n\nstderr:\n",
)
_QUOTED_TRANSITIONS = (
    (
        'The approval policy changed from "',
        '" to "',
        '" (changed by the user).',
    ),
    ('The user changed the approval policy from "', '" to "', '".'),
    ('The working directory changed from "', '" to "', '".'),
)


def _body(rendered_text: str) -> str:
    text = rendered_text.replace("\r\n", "\n").replace("\r", "\n").strip()
    newline = text.find("\n")
    if newline < 0:
        return text
    header = text[:newline]
    prefix, suffix = "### ", ". user"
    if not header.startswith(prefix) or not header.endswith(suffix):
        return text
    digits = header[len(prefix) : -len(suffix)]
    valid = digits.isascii() and digits.isdigit()
    return text[newline + 1 :].strip() if valid else text


def _has_hard_exclusion(body: str) -> bool:
    folded = body.casefold()
    if any(tag in folded for tag in _HARD_TAGS):
        return True
    if "This is an automatically generated checkpoint" in body:
        return True
    for line in body.splitlines():
        line = line.strip()
        if line.startswith("Agent ") and " sent a message:" in line[6:]:
            return True
    return False


def _only_reminders(body: str) -> bool:
    folded = body.casefold()
    offset = 0
    found = False
    while offset < len(folded):
        while offset < len(folded) and folded[offset].isspace():
            offset += 1
        if offset == len(folded):
            return found
        if not folded.startswith(_REMINDER_OPEN, offset):
            return False
        content = offset + len(_REMINDER_OPEN)
        close = folded.find(_REMINDER_CLOSE, content)
        if close < 0:
            return False
        nested = folded.find(_REMINDER_OPEN, content, close)
        if nested >= 0:
            return False
        offset = close + len(_REMINDER_CLOSE)
        found = True
    return found


def _quoted_transition(body: str, prefix: str, middle: str, suffix: str) -> bool:
    if not body.startswith(prefix) or not body.endswith(suffix):
        return False
    inner = body[len(prefix) : -len(suffix)]
    before, separator, after = inner.partition(middle)
    if not separator or not before or not after:
        return False
    invalid = '"\n'
    return not any(char in before or char in after for char in invalid)


def _runtime_snapshot(body: str) -> bool:
    for prefix in _RUNTIME_PREFIXES:
        if body == prefix:
            return True
        if not body.startswith(prefix):
            continue
        rest = body[len(prefix) :]
        if rest.startswith("\n\n"):
            rest = rest[2:]
        elif rest.startswith("\n"):
            rest = rest[1:]
        else:
            continue
        if rest.startswith('Current working directory: "') and rest.endswith('".'):
            value = rest[28:-2]
            return bool(value) and not any(char in value for char in '"\n')
    return False


def _model_selection(body: str) -> bool:
    prefix = "[model changed: assistant turns above this point were generated by "
    middle = "; the session continues with "
    if not body.startswith(prefix) or not body.endswith("]"):
        return False
    first, separator, second = body[len(prefix) : -1].partition(middle)
    if not separator or not first or not second:
        return False
    return not any(char in first or char in second for char in "[]\r\n;")


def _job_notice(body: str) -> bool:
    match = _JOB_HEAD_RE.match(body)
    if match is None:
        return False
    tail = body[match.end() :]
    if not tail:
        return True
    marker = next((item for item in _JOB_OUTPUT_MARKERS if tail.startswith(item)), "")
    if not marker:
        return False
    output = tail[len(marker) :]
    return bool(output) and "\n\n" not in output


def _repeated_call_signature(body: str) -> bool:
    if "\n" in body or not body.isascii():
        return False
    prefix = "Repeated tool call detected: "
    if not body.startswith(prefix):
        return False
    call = body[len(prefix) :].removesuffix(".")
    if not call.endswith(")"):
        return False
    name, sep, rest = call[:-1].partition("(")
    if sep != "(" or _REPEATED_CALL_NAME_RE.fullmatch(name) is None:
        return False
    if "(" in rest or ")" in rest:
        return False
    if not rest:
        return True
    return all(
        _REPEATED_CALL_ARG_RE.fullmatch(item.strip(" ")) is not None
        for item in rest.split(",")
    )


def _repeat_notice(body: str) -> bool:
    return body in _EXACT_REPEAT_NOTICES or _repeated_call_signature(body)


def is_synthetic_user_block(rendered_text: str) -> bool:
    """Return whether all non-whitespace body text is a known service injection."""
    body = _body(rendered_text)
    if not body or _has_hard_exclusion(body):
        return False
    if _only_reminders(body) or _runtime_snapshot(body):
        return True
    if _NOTICE_RE.fullmatch(body) is not None:
        return True
    if any(_quoted_transition(body, *spec) for spec in _QUOTED_TRANSITIONS):
        return True
    return _model_selection(body) or _job_notice(body) or _repeat_notice(body)
