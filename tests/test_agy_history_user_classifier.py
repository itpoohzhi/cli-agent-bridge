"""Boundary tests for the pure synthetic user-history classifier (AD-001)."""

from __future__ import annotations

import ast
import sys
from pathlib import Path
from time import perf_counter

import pytest

ROOT = Path(__file__).resolve().parents[1]
BRIDGE_DIR = ROOT / "bridges" / "agy-bridge"
CLASSIFIER_PATH = BRIDGE_DIR / "agy_runtime" / "history_user_classifier.py"
sys.path.insert(0, str(BRIDGE_DIR))
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from agy_runtime.history_user_classifier import is_synthetic_user_block  # noqa: E402


REMINDER = "<system-reminder>runtime context</system-reminder>"
LEGACY_CASES = (
    "Current runtime context. This snapshot supersedes earlier snapshots.",
    "Current runtime context. This snapshot supersedes earlier runtime-context snapshots.",
    "Current runtime context. This snapshot supersedes earlier snapshots.\n\n"
    'Current working directory: "/tmp/project".',
    'The approval policy changed from "ask" to "allow" (changed by the user).',
    "The user approved the bash command.",
    "The user rejected tool call",
)
DSH_CASES = (
    'The user changed the approval policy from "ask" to "danger-full-access".',
    "[model changed: assistant turns above this point were generated by model-a; "
    "the session continues with model-b]",
    'The working directory changed from "/old" to "/new".',
    "background job bash-42 (pytest tests/) finished [status: completed].",
    "background job bash-42 (pytest tests/) finished [status: failed].\n\n"
    "Output:\nexit code 1",
    "You are repeating the exact same tool call. Reconsider your approach.",
    "Repeated tool call detected: read_file(path=README.md)",
)


@pytest.mark.parametrize("body", (REMINDER, *LEGACY_CASES, *DSH_CASES))
@pytest.mark.parametrize("header", ("", "### 2. user\n", "### 2. user\r\n"))
def test_known_service_formats_are_synthetic(body: str, header: str) -> None:
    assert is_synthetic_user_block(f"  {header}{body}  ")


def test_multiple_case_insensitive_reminders_with_whitespace() -> None:
    body = (
        "<SYSTEM-REMINDER>one</SYSTEM-REMINDER>\n \t\n"
        "<system-reminder>two</system-reminder>"
    )
    assert is_synthetic_user_block(body)


@pytest.mark.parametrize(
    "body",
    (
        "<system-reminder>unfinished",
        "before <system-reminder>one</system-reminder>",
        "<system-reminder>one</system-reminder> between "
        "<system-reminder>two</system-reminder>",
        "<system-reminder>one</system-reminder> after",
        "<system-reminder>outer <system-reminder>nested</system-reminder>",
        "I saw <system-reminder>quoted</system-reminder> in the prompt.",
    ),
)
def test_reminders_require_complete_full_body_coverage(body: str) -> None:
    assert not is_synthetic_user_block(body)


@pytest.mark.parametrize(
    "body",
    (
        "<goal_round>continue</goal_round>",
        "<GOAL_BLOCKED>need input</GOAL_BLOCKED> " + REMINDER,
        "<goal_complete>done</goal_complete>",
        "<compacted-summary>important context</compacted-summary>",
        "This is an automatically generated checkpoint. " + REMINDER,
        "Agent worker-1 sent a message:\nkeep this fact",
    ),
)
def test_hard_exclusions_always_remain_real(body: str) -> None:
    assert not is_synthetic_user_block(body)


@pytest.mark.parametrize(
    "body",
    (
        REMINDER + "\nCheck this",
        DSH_CASES[0] + " check why",
        DSH_CASES[1] + " investigate",
        DSH_CASES[2] + " Is that correct?",
        DSH_CASES[3] + " check why",
        DSH_CASES[4] + "\n\nWhy did it fail?",
        DSH_CASES[5] + "\n\nPlease continue anyway.",
        DSH_CASES[6] + "\n\nWhy?",
        "background job failed, check why",
        "The user approved this plan; implement it.",
    ),
)
def test_mixed_or_unknown_user_input_is_not_synthetic(body: str) -> None:
    assert not is_synthetic_user_block(body)


@pytest.mark.parametrize(
    "text",
    (
        "",
        " \r\n\t ",
        "### 2. user\n   ",
        "intro\n" + REMINDER,
        "### x. user\n" + REMINDER,
        "### 2. assistant\n" + REMINDER,
        "### 2. user " + REMINDER,
    ),
)
def test_empty_and_inexact_headers_are_not_synthetic(text: str) -> None:
    assert not is_synthetic_user_block(text)


def test_four_mib_adversarial_input_is_linear_time() -> None:
    text = "<system-reminder>" * ((4 * 1024 * 1024) // 17)
    started = perf_counter()
    assert not is_synthetic_user_block(text)
    assert perf_counter() - started < 0.5


def test_classifier_module_satisfies_purity_and_size_contract() -> None:
    source = CLASSIFIER_PATH.read_text(encoding="utf-8")
    tree = ast.parse(source)
    assert len(source.splitlines()) <= 200
    forbidden = {
        "os", "sys", "httpx", "subprocess", "fastapi", "pathlib", "logging",
        "time", "server", "long_session_config",
    }
    imports = {
        alias.name.split(".")[0]
        for node in ast.walk(tree)
        if isinstance(node, (ast.Import, ast.ImportFrom))
        for alias in node.names
    }
    assert not imports & forbidden
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            assert node.end_lineno is not None
            assert node.end_lineno - node.lineno + 1 <= 40
            assert len(node.args.args) <= 5
            branches = sum(
                1
                for item in ast.walk(node)
                if isinstance(item, (ast.If, ast.For, ast.While, ast.IfExp, ast.ExceptHandler))
            )
            boolean_branches = sum(
                len(item.values) - 1
                for item in ast.walk(node)
                if isinstance(item, ast.BoolOp)
            )
            assert 1 + branches + boolean_branches <= 10
        if isinstance(node, (ast.Assign, ast.AnnAssign)) and node.col_offset == 0:
            value = node.value
            assert not isinstance(value, (ast.List, ast.Dict, ast.Set))
